package com.referralportal.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.time.Instant;

@Entity
@Table(name = "referral_request_credits")
public class ReferralRequestCredit {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @ManyToOne
    @JoinColumn(name = "source_response_id", nullable = false, unique = true)
    private ReferralRequestResponse sourceResponse;

    @ManyToOne
    @JoinColumn(name = "consumed_by_request_id", unique = true)
    private CompanyReferralRequest consumedByRequest;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    @Column(name = "expires_at", nullable = false)
    private Instant expiresAt;

    @Column(name = "consumed_at")
    private Instant consumedAt;

    public Long getId() {
        return id;
    }

    public User getUser() {
        return user;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public ReferralRequestResponse getSourceResponse() {
        return sourceResponse;
    }

    public void setSourceResponse(ReferralRequestResponse sourceResponse) {
        this.sourceResponse = sourceResponse;
    }

    public CompanyReferralRequest getConsumedByRequest() {
        return consumedByRequest;
    }

    public void setConsumedByRequest(CompanyReferralRequest consumedByRequest) {
        this.consumedByRequest = consumedByRequest;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getExpiresAt() {
        return expiresAt;
    }

    public void setExpiresAt(Instant expiresAt) {
        this.expiresAt = expiresAt;
    }

    public Instant getConsumedAt() {
        return consumedAt;
    }

    public void setConsumedAt(Instant consumedAt) {
        this.consumedAt = consumedAt;
    }
}